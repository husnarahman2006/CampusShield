#!/usr/bin/env python3
"""
CampusShield - Block Rule Generator (Stage 3: DPI enforcement, proof of concept)

WHAT: Reads the blocked domains from the CampusShield database and writes them
      as Suricata "drop" rules that match the TLS SNI (the website name in the
      TLS Client Hello).

WHY:  The domain list and the policies live in PostgreSQL (Stage 2), so the
      administrator changes the database, not the code. This script turns the
      database into rules Suricata understands. Run it again after changing
      the domain list, then restart Suricata.

WHICH DOMAINS (proof of concept): every domain whose category is BLOCK for
      the 'student' role during class. Role- and timetable-based decisions
      per user come later (Stage 2 matcher + Stage 5).

USAGE:
  sudo python3 generate_block_rules.py                       # write the default rule file
  sudo python3 generate_block_rules.py --out /tmp/test.rules # write somewhere else (testing)
"""

import argparse   # command-line options
import re         # checks that each domain contains only safe characters
import subprocess # runs psql inside the database container
import sys        # error messages and exit codes

DEFAULT_OUT = "/etc/suricata/rules/campusshield.rules"
DB_CONTAINER = "campusshield-db"   # container name from docker-compose.yml
DB_USER = "campusshield"
DB_NAME = "campusshield"

# Local rule IDs. Suricata/Snort reserve 1,000,000-1,999,999 for local rules,
# so these never clash with the Emerging Threats rules (2,000,000 and above).
SID_START = 1000001

# Domains to block = domains whose category the student policy blocks during class.
QUERY = """
SELECT DISTINCT d.domain, d.category
FROM domain_categories d
JOIN policies p ON p.category = d.category
WHERE p.role = 'student' AND p.during_class = 'BLOCK'
ORDER BY d.category, d.domain;
"""

# A valid domain: letters, digits, hyphens and dots only.
# Why: the domain is written into a rule file; rejecting anything else stops a
# bad database entry (e.g. containing ; or ") from breaking or changing a rule.
DOMAIN_RE = re.compile(r"^[a-z0-9-]+(\.[a-z0-9-]+)+$")


def fetch_domains():
    """Return a list of (domain, category) rows from the database."""
    cmd = ["docker", "exec", DB_CONTAINER,
           "psql", "-U", DB_USER, "-d", DB_NAME,
           "-At",          # -A unaligned, -t tuples only: plain "domain|category" lines
           "-F", "|",      # field separator
           "-c", QUERY]
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
    except FileNotFoundError:
        sys.exit("docker not found")
    except subprocess.CalledProcessError as e:
        sys.exit(f"Database query failed (is the database running?):\n{e.stderr}")

    rows = []
    for line in out.splitlines():
        if "|" not in line:
            continue
        domain, category = line.split("|", 1)
        domain = domain.strip().lower()
        if not DOMAIN_RE.match(domain):
            print(f"[!] skipped invalid domain: {domain!r}", file=sys.stderr)
            continue
        rows.append((domain, category.strip()))
    return rows


def make_rule(domain, category, sid):
    """Build one Suricata drop rule for a domain and all its subdomains.

    How the match works:
      tls.sni      -> look only at the SNI field of the TLS Client Hello
      dotprefix    -> put a "." in front of the SNI before comparing
      content:".facebook.com"; endswith;
                   -> the SNI must END with ".facebook.com"
    So "facebook.com" (".facebook.com") and "www.facebook.com" match,
    but a look-alike "notfacebook.com" (".notfacebook.com") does not.
    nocase       -> upper/lower case does not matter
    flow:to_server,established -> only client-to-server packets of a real connection
    drop         -> in IPS mode, drop the packet and the rest of the connection
    """
    return (f'drop tls any any -> any any '
            f'(msg:"CampusShield BLOCK {category} {domain}"; '
            f'flow:to_server,established; '
            f'tls.sni; dotprefix; content:".{domain}"; endswith; nocase; '
            f'classtype:policy-violation; sid:{sid}; rev:1;)')


def main():
    parser = argparse.ArgumentParser(description="Generate Suricata SNI block rules from the database")
    parser.add_argument("--out", default=DEFAULT_OUT, help="rule file to write")
    args = parser.parse_args()

    rows = fetch_domains()
    if not rows:
        sys.exit("No domains to block were found in the database.")

    lines = ["# CampusShield SNI block rules - generated by generate_block_rules.py",
             "# Do not edit by hand: change the database and run the script again."]
    for i, (domain, category) in enumerate(rows):
        lines.append(make_rule(domain, category, SID_START + i))

    try:
        with open(args.out, "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
    except PermissionError:
        sys.exit(f"No permission to write {args.out} (run with sudo)")

    print(f"[+] {len(rows)} block rules written to {args.out}")
    for domain, category in rows:
        print(f"    {category:<16} {domain}")


if __name__ == "__main__":
    main()
